import type { StyleSpecification } from 'maplibre-gl';

import { WORLD_MAX_ZOOM, warpedWorldStyle } from './worldStyle';

/**
 * Everything about the map that can be decided without a map instance, kept pure so that it is testable
 * and so that the camera constraints live in one readable place.
 */

/** A real Earth to compare against, reachable by setting the style in the environment. */
export const EARTH_STYLE_URL = 'https://tiles.openfreemap.org/styles/positron';

/**
 * The player's camera: tipped back and north-up, parallel, and showing the world once. Tipped north-up
 * with no perspective, the ground is foreshortened by the cosine of the tip and nothing else, which keeps
 * the sprite overlay a handful of multiplies against the map centre and lets everything laid out as if
 * the map were flat be drawn right by squashing its height. See docs/adr/0058, which superseded the flat
 * camera of 0014. Pulled back far enough, the world is a sheet lying on a desk; the rule for that is in
 * map/sheet.ts. See docs/adr/0033.
 */
export const CAMERA = {
  /** The northern reach of our world, which is a warped northern Europe. */
  center: { lng: 10.5, lat: 55.5 },
  initialZoom: 4,
  /**
   * MapLibre's own hard floor, below which it refuses a minimum zoom. The floor that is felt is
   * `floorZoom` in map/sheet.ts, which depends on the size of the window.
   */
  minZoom: -2,
  maxZoom: WORLD_MAX_ZOOM,
  /** At the floor the sheet is this much of the window's shorter side: half, so the desk shows around it. */
  sheetAtFloor: 0.5,
  /**
   * How far the camera is tipped back from straight down, in degrees. A square of ground is drawn 1.41
   * times as wide as it is tall, and the scenery and the marks stand up on it. Adam's choice, from the
   * Camera section of the debug panel, where it can still be pulled either way.
   */
  pitch: 45,
  /** Which way is up. North, so the tip only ever squashes the height of the ground, never turns it. */
  bearing: 0,
  /**
   * The grid the ground's colour is read on: turned twenty-six degrees so a cell is a diamond while north
   * stays up, four world units across, which is the size the diamonds button draws. See experiment 0008.
   */
  lattice: { turn: 26, size: 4 },
} as const;

/** MapLibre's own field of view, which is what a camera standing in the world looks like. */
export const WIDE_FOV = 36.86989764584402;

/**
 * How far the field of view closes when the camera tips, which is MapLibre's own clamp.
 *
 * It goes all the way to the clamp because anything short of it is measurably not parallel, and the
 * overlay's projection is the fov-nothing limit exactly. Measured at sixty degrees of tilt, the worst
 * disagreement anywhere on the screen between where the map draws the ground and where the overlay
 * draws a thing standing on it is about **ten pixels for every degree** of field of view: ten at one
 * degree, one at a tenth. See experiment 0008.
 */
export const PARALLEL_FOV = 0.1;

/**
 * How wide the camera sees, which follows from how far it has tipped and is nobody's to set.
 *
 * Tipped, it is parallel, always. The marks and the scenery are placed by a projection that is exact for
 * a parallel camera and hundreds of pixels wrong for a wide one, so a tipped camera with a wide lens
 * would slide every tree off its ground - and a combination of settings that can do that is a glitch hunt
 * waiting for somebody to reach it by accident. So there is no such combination. Flat, it is MapLibre's
 * own, which looks exactly the same straight down.
 */
export function lensFor(pitch: number): number {
  return pitch > 0 ? PARALLEL_FOV : WIDE_FOV;
}

/**
 * Our own world by default, generated by the world package and served as files, with no roads, no towns
 * and no text. Setting a style URL in the environment swaps in someone else's map instead, which is how
 * we look at the real Earth for comparison.
 */
export function resolveStyle(
  env: { VITE_MAP_STYLE_URL?: string },
  worldRoot: string,
): string | StyleSpecification {
  const configured = env.VITE_MAP_STYLE_URL?.trim();
  return configured !== undefined && configured !== '' ? configured : warpedWorldStyle(worldRoot);
}
