import type { StyleSpecification } from 'maplibre-gl';

import { WORLD_MAX_ZOOM, warpedWorldStyle } from './worldStyle';

/**
 * Everything about the map that can be decided without a map instance, kept pure so that it is testable
 * and so that the camera constraints live in one readable place.
 */

/** A real Earth to compare against, reachable by setting the style in the environment. */
export const EARTH_STYLE_URL = 'https://tiles.openfreemap.org/styles/positron';

/**
 * The camera is flat, north-up and shows the world once, which keeps the sprite overlay a two-multiply
 * projection against the map centre. See docs/adr/0014.
 */
export const CAMERA = {
  /** The northern reach of our world, which is a warped northern Europe. */
  center: { lng: 10.5, lat: 55.5 },
  initialZoom: 4,
  minZoom: 2,
  maxZoom: WORLD_MAX_ZOOM,
} as const;

/**
 * Our own world by default, generated by the world package and served as files, with no roads, no towns
 * and no text. Setting a style URL in the environment swaps in someone else's map instead, which is how
 * we look at the real Earth for comparison.
 */
export function resolveStyle(
  env: { VITE_MAP_STYLE_URL?: string },
  worldRoot: string,
): string | StyleSpecification {
  const configured = env.VITE_MAP_STYLE_URL?.trim();
  return configured !== undefined && configured !== '' ? configured : warpedWorldStyle(worldRoot);
}
