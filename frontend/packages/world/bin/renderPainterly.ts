import { readFileSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { deflateSync } from 'node:zlib';
import { resolve } from 'node:path';

import { PNG } from 'pngjs';

import { preparePalette, snapPrepared, toRgb } from '../src/palette.ts';
import type { Palette, Rgb } from '../src/palette.ts';
import { createRaster } from '../src/raster.ts';
import type { ClassRaster } from '../src/raster.ts';
import { encodeRgbPng } from '../src/png.ts';
import type { RgbImage } from '../src/png.ts';
import { paintPixel, preparePainterly } from '../src/painterly.ts';
import { masterRowsAt } from '../src/tiles.ts';
import type { ClassSampler, PainterlyStyle, PreparedPainterly } from '../src/painterly.ts';

import { MASTER_DIR, OUTPUT_DIR, PAINTERLY, PAINTERLY_DIR, PALETTE, RENDER } from './paths.ts';

/**
 * Paints views of the world, in every style, to settle what the world looks like.
 *
 * Stills rather than the live map, because a still can be any size and arrives in a second, and because
 * the same functions paint both: the app draws tiles with `paintPixel` through a custom protocol, so
 * there is one implementation of the look and this is the place it is judged. See docs/adr/0021 and 0022.
 *
 * Every view is written flat once and then once per style, because the only useful judgement is the
 * comparison. It also writes the runtime copy of the styles that the app fetches.
 *
 *   node bin/renderPainterly.ts [--view name] [--style name] [--out dir] [--width px] [--config-only]
 */

const args = process.argv.slice(2);
const flag = (name: string): string | undefined => {
  const at = args.indexOf(`--${name}`);
  return at < 0 ? undefined : args[at + 1];
};

interface View {
  name: string;
  lng: [number, number];
  lat: [number, number];
  width: number;
}

const outputDir = flag('out') ?? PAINTERLY_DIR;
const palette = JSON.parse(await readFile(PALETTE, 'utf8')) as Palette;
const render = JSON.parse(await readFile(RENDER, 'utf8')) as { colours: Record<string, string> };
const file = JSON.parse(await readFile(PAINTERLY, 'utf8')) as {
  styles: Record<string, PainterlyStyle>;
  views: View[];
};

/** Every style prepared up front, so an unusable one is reported before the master is read. */
const prepared = new Map<string, PreparedPainterly>();
for (const [name, style] of Object.entries(file.styles)) {
  try {
    prepared.set(name, preparePainterly(style, palette, render.colours));
  } catch (cause) {
    throw new Error(`the ${name} style is unusable: ${(cause as Error).message}`, { cause });
  }
}

/**
 * The runtime copy the app reads, written before anything else so that `--config-only` costs a second
 * rather than the eight it takes to read the master. The app prepares these styles with the same
 * function this script does, against the same palette and the same colours.
 */
await mkdir(OUTPUT_DIR, { recursive: true });
const runtime = {
  $comment: 'Generated by npm run world:paint. Edit world/painterly.json, not this.',
  palette: {
    master: palette.master,
    classes: palette.classes.map((terrain) => ({
      id: terrain.id,
      name: terrain.name,
      colour: terrain.colour,
      water: terrain.water === true,
      group: terrain.group ?? 'none',
    })),
  },
  colours: render.colours,
  styles: file.styles,
};
await writeFile(resolve(OUTPUT_DIR, 'paint.json'), `${JSON.stringify(runtime, null, 2)}\n`);
console.log(`wrote ${resolve(OUTPUT_DIR, 'paint.json')}, ${Object.keys(file.styles).length} styles`);

if (args.includes('--config-only')) {
  console.log('config only, so the master was not read and no images were painted');
  process.exit(0);
}

/** The flat look, for the comparison: the colour of the class, and nothing else. */
const flatColours: Rgb[] = [];
for (let id = 0; id <= Math.max(...palette.classes.map((terrain) => terrain.id)); id += 1) {
  const terrain = palette.classes.find((candidate) => candidate.id === id);
  flatColours.push(toRgb(terrain === undefined ? '#000000' : render.colours[terrain.name]!));
}

const oneView = flag('view');
const views = oneView === undefined ? file.views : file.views.filter((view) => view.name === oneView);
if (views.length === 0) {
  throw new Error(`no view called ${oneView}; there is ${file.views.map((v) => v.name).join(', ')}`);
}

const oneStyle = flag('style');
const styles =
  oneStyle === undefined ? [...prepared.keys()] : [...prepared.keys()].filter((n) => n === oneStyle);
if (styles.length === 0) {
  throw new Error(`no style called ${oneStyle}; there is ${[...prepared.keys()].join(', ')}`);
}

/**
 * The master, as one class per pixel. Read inside a function so the two gigabytes of RGBA that pngjs
 * hands back can be collected before any painting starts.
 */
function readMaster(): ClassRaster {
  const started = Date.now();
  const decoded = PNG.sync.read(readFileSync(resolve(MASTER_DIR, 'terrain.png')));
  const world = createRaster(decoded.width, decoded.height);
  const memo = new Int16Array(1 << 24).fill(-1);
  const preparedPalette = preparePalette(palette);

  for (let index = 0; index < world.cells.length; index += 1) {
    const at = index * 4;
    const red = decoded.data[at]!;
    const green = decoded.data[at + 1]!;
    const blue = decoded.data[at + 2]!;
    const colour = (red << 16) | (green << 8) | blue;
    let id = memo[colour]!;
    if (id < 0) {
      id = snapPrepared([red, green, blue], preparedPalette).id;
      memo[colour] = id;
    }
    world.cells[index] = id;
  }

  console.log(
    `master ${world.width} by ${world.height}, read in ${((Date.now() - started) / 1000).toFixed(1)}s`,
  );
  return world;
}

const RADIANS = Math.PI / 180;

/** Web Mercator's vertical coordinate, running to plus or minus pi. World space is a scaling of it. */
function mercatorY(latitude: number): number {
  return Math.log(Math.tan(Math.PI / 4 + (latitude * RADIANS) / 2));
}

/**
 * How much of the world one pixel of a view covers, in world-space units, which is all the paint knows
 * of a view. Both are linear in longitude, so across is a scaling; down needs no separate answer because
 * world space is square.
 */
function groundPerPixel(view: View, world: ClassRaster, width: number): number {
  return (world.width * ((view.lng[1] - view.lng[0]) / 360)) / width;
}

/**
 * One view, in one style, or flat when no style is given.
 *
 * The view is Web Mercator so that it is directly comparable with a screenshot of the running map, and
 * world space is Mercator too, so a row of the view is a row of world space and nothing here converts a
 * latitude. The projection happens once, on the way into the master, in `classAt`. See decision 0030.
 */
function renderView(
  view: View,
  world: ClassRaster,
  classAt: ClassSampler,
  style: PreparedPainterly | undefined,
): RgbImage {
  const [west, east] = view.lng;
  const [south, north] = view.lat;
  const width = Number(flag('width') ?? view.width);
  const top = mercatorY(north);
  const bottom = mercatorY(south);
  const height = Math.max(1, Math.round((width * (top - bottom)) / ((east - west) * RADIANS)));
  const masterPerPixel = groundPerPixel(view, world, width);

  const pixels = new Uint8Array(width * height * 3);
  let at = 0;

  for (let row = 0; row < height; row += 1) {
    const mercator = top - ((top - bottom) * (row + 0.5)) / height;
    const worldY = (0.5 - mercator / (2 * Math.PI)) * world.width;
    for (let column = 0; column < width; column += 1) {
      const longitude = west + ((east - west) * (column + 0.5)) / width;
      const worldX = ((longitude + 180) / 360) * world.width;
      const colour =
        style === undefined
          ? (flatColours[classAt(worldX, worldY)] ?? flatColours[0]!)
          : paintPixel(style, classAt, worldX, worldY, masterPerPixel);
      pixels[at] = colour[0];
      pixels[at + 1] = colour[1];
      pixels[at + 2] = colour[2];
      at += 3;
    }
  }

  return { width, height, pixels };
}

const world = readMaster();

/** World space is Mercator and the master is not, so every row of it is projected once, up front. */
const masterRowOf = masterRowsAt(world.width, world.height);

/**
 * Nearest, always: the average of two terrains is a third terrain. Longitude wraps, because the world
 * does; latitude clamps, because it does not.
 */
const classAt: ClassSampler = (x, y) => {
  const column = ((Math.floor(x) % world.width) + world.width) % world.width;
  const down = Math.min(world.width - 1, Math.max(0, Math.floor(y)));
  return world.cells[masterRowOf[down]! * world.width + column]!;
};

await mkdir(outputDir, { recursive: true });
const deflate = (data: Uint8Array) => new Uint8Array(deflateSync(data, { level: 6 }));

console.log(`\npainting ${views.length} view(s) in ${styles.length} style(s), into ${outputDir}\n`);
let written = 0;

for (const view of views) {
  const jobs: [string, PreparedPainterly | undefined][] = [[`${view.name}-flat`, undefined]];
  for (const name of styles) {
    jobs.push([`${view.name}-${name}`, prepared.get(name)]);
  }

  for (const [name, style] of jobs) {
    const started = Date.now();
    const image = renderView(view, world, classAt, style);
    const png = encodeRgbPng(image, deflate);
    await writeFile(resolve(outputDir, `${name}.png`), png);
    written += 1;

    const perPixel = groundPerPixel(view, world, image.width);
    console.log(
      `  ${`${name}.png`.padEnd(26)} ${(png.length / 1048576).toFixed(1)} MB  ` +
        `${((Date.now() - started) / 1000).toFixed(1)}s  ${image.width} by ${image.height}, ` +
        `${perPixel.toFixed(2)} master pixels a pixel, about zoom ${(7 - Math.log2(perPixel)).toFixed(1)}`,
    );
  }
}

console.log(`\n${written} images. Each view is flat once and then once per style, so they compare.`);
