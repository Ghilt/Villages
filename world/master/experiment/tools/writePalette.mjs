/**
 * Writes the two files that say what the colours mean: palette.txt for a person, palette.json for a
 * program. The picture is drawn by drawPalette.ps1, which reads the JSON this leaves behind.
 *
 *   node writePalette.mjs [--out <directory>]
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { CLASSES, GROUPS, closestPair } from './palette.mjs';

const args = new Map();
for (let i = 2; i < process.argv.length; i += 2) {
  args.set(process.argv[i].replace(/^--/, ''), process.argv[i + 1]);
}
const OUT = resolve(args.get('out') ?? resolve(import.meta.dirname, '..'));
mkdirSync(OUT, { recursive: true });

const worst = closestPair();

const GROUP_TITLE = {
  water: 'Water',
  cold: 'Cold and bare',
  forest: 'Forest',
  open: 'Open land',
  farmed: 'Farmed land',
  wetland: 'Wetland',
  dry: 'Dry land',
  high: 'High ground',
};

const lines = [
  'The experimental terrain palette: 32 classes',
  '============================================',
  '',
  'One flat colour per terrain class in terrain.png, which is an 8-bit indexed PNG of 16384 by 8192,',
  'unprojected: longitude runs -180 to 180 left to right, latitude 90 to -90 top to bottom. One pixel is',
  'about 2.4 km north to south, and 2.4 km east to west at the equator.',
  '',
  'The colours are DATA, not a look. They exist so a person can tell classes apart while painting and so',
  'the importer can snap any pixel back to exactly one class. What a forest looks like in the game is the',
  `renderer's business. No two classes are closer than ${worst.distance.toFixed(0)} apart in straight-line RGB distance`,
  `(closest pair: ${worst.a} and ${worst.b}).`,
  '',
  'Paint with the Pencil, not the Brush. Anti-aliasing off, bucket tolerance zero, interpolation set to',
  'Nearest Neighbour. See docs/AUTHORING-THE-WORLD.md.',
  '',
  // Built from the same padding as the rows below, so the columns cannot drift apart.
  ['id', 'name'.padEnd(20), 'hex'.padEnd(8), 'kind'.padEnd(5), 'what it means'].join('  '),
  ['--', '-'.repeat(20), '-'.repeat(8), '-'.repeat(5), '-'.repeat(61)].join('  '),
];

for (const group of GROUPS) {
  for (const terrain of CLASSES.filter((c) => c.group === group)) {
    lines.push(
      [
        String(terrain.id).padStart(2),
        terrain.name.padEnd(20),
        terrain.colour.padEnd(8),
        (terrain.water === true ? 'water' : 'land').padEnd(5),
        terrain.meaning,
      ].join('  '),
    );
  }
  lines.push('');
}

lines.push('Just the codes, in id order, for pasting into a swatch file:');
lines.push('');
for (const terrain of CLASSES) {
  lines.push(`${terrain.colour}  ${terrain.name}`);
}
lines.push('');

writeFileSync(join(OUT, 'palette.txt'), `${lines.join('\n')}\n`, 'utf8');

writeFileSync(
  join(OUT, 'palette.json'),
  `${JSON.stringify(
    {
      $comment:
        'The experimental 32-class palette. Same shape as world/palette.json plus a group and a meaning per class, so the two can be compared directly. Generated by world/master/experiment/tools/writePalette.mjs.',
      master: { width: 16384, height: 8192, projection: 'equirectangular' },
      minimumClassDistance: Math.floor(worst.distance),
      groupTitles: GROUP_TITLE,
      classes: CLASSES,
    },
    null,
    2,
  )}\n`,
  'utf8',
);

console.log(`palette.txt and palette.json written to ${OUT}`);
console.log(`${CLASSES.length} classes, closest pair ${worst.distance.toFixed(1)} (${worst.a} / ${worst.b})`);
